import AppKit
import CryptoKit
import Foundation

/// One remembered clipboard entry.
struct ClipItem: Identifiable, Equatable, Sendable, Codable {
    enum Kind: String, Codable, Sendable {
        case text, link, code, image, files
    }

    let id: UUID
    let kind: Kind
    /// Text, link or code; for files, their paths joined by newlines.
    var text: String?
    /// Orilio's copy of an image, `<id>.png` inside the clipboard folder.
    var imageFileName: String?
    var imageSize: CGSize?
    var copiedAt: Date
    var sourceApp: String?
    var pinned: Bool
    /// SHA-256 of the content, to tell a repeat from a new copy.
    let contentHash: String

    var fileURLs: [URL] {
        kind == .files ? (text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : []
    }

    /// The one-line text a row shows.
    var preview: String {
        switch kind {
        case .image:
            let size = imageSize.map { "\(Int($0.width)) × \(Int($0.height))" }
            return ["Image", size].compactMap { $0 }.joined(separator: " · ")
        case .files:
            let names = fileURLs.map(\.lastPathComponent)
            return names.count == 1 ? names[0] : "\(names.count) files: \(names.prefix(3).joined(separator: ", "))"
        default:
            return (text ?? "").replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        }
    }
}

/// What a pasteboard change contained, already filtered and classified. Pure.
enum ClipContent: Equatable, Sendable {
    case text(String, ClipItem.Kind)
    case image(Data)
    case files([URL])

    var hash: String {
        var hasher = SHA256()
        switch self {
        case .text(let text, _): hasher.update(data: Data("t:\(text)".utf8))
        case .image(let data): hasher.update(data: Data("i:".utf8)); hasher.update(data: data)
        case .files(let urls): hasher.update(data: Data("f:\(urls.map(\.path).joined(separator: "\n"))".utf8))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

enum ClipboardPolicy {
    /// Markers that apps put on content which shouldn't be remembered (nspasteboard.org
    /// conventions and known password managers). Not every app sets them; Orilio doesn't claim
    /// to recognize every secret.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Never record what is copied while these apps are in front.
    static let defaultExcludedApps: [String] = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc",
    ]

    /// Images above this size are skipped rather than kept in the history.
    static let maxImageBytes = 20 * 1024 * 1024
    /// Text is cut to this length when stored.
    static let maxTextLength = 50_000

    static func isPrivate(types: [String]) -> Bool {
        types.contains(where: privateTypes.contains)
    }

    /// Text that looks like a URL is a link; a single line that looks like a command or an
    /// assignment is code (shown in monospace); everything else is text.
    static func kind(of text: String) -> ClipItem.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
           let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host != nil {
            return .link
        }
        let commands = #"^(\$ )?(sudo |kubectl|git|npm|npx|yarn|pnpm|brew|docker|ssh|scp|curl|wget|swift|xcodebuild|python3?|pip3?|make|cd|ls|rm|cp|mv|cat|grep|export|terraform|aws|gcloud|helm|node|go|cargo)\b"#
        let assignment = #"^[A-Z_][A-Z0-9_]*=\S+$"#
        if !trimmed.contains("\n"),
           trimmed.range(of: commands, options: .regularExpression) != nil
            || trimmed.range(of: assignment, options: .regularExpression) != nil {
            return .code
        }
        return .text
    }

    /// "now", "1 min", "6 min", "2 h", "3 d".
    static func age(of date: Date, at now: Date) -> String {
        let seconds = Int(now.timeIntervalSince(date))
        if seconds < 60 { return "now" }
        if seconds < 3_600 { return "\(seconds / 60) min" }
        if seconds < 86_400 { return "\(seconds / 3_600) h" }
        return "\(seconds / 86_400) d"
    }

    /// Applies the size and age limits. Pinned items are never pruned.
    static func prune(_ items: [ClipItem], maxItems: Int, maxAge: TimeInterval?, now: Date) -> [ClipItem] {
        var kept = items.filter { item in
            item.pinned || maxAge.map { now.timeIntervalSince(item.copiedAt) <= $0 } ?? true
        }
        let unpinned = kept.filter { !$0.pinned }
        if unpinned.count > maxItems {
            let drop = Set(unpinned.sorted { $0.copiedAt > $1.copiedAt }.dropFirst(maxItems).map(\.id))
            kept.removeAll { drop.contains($0.id) }
        }
        return kept
    }

    /// Image files are always `<id>.png`; anything else in stored data is ignored (no path tricks).
    static func isManagedImageName(_ name: String, id: UUID) -> Bool {
        name == "\(id.uuidString).png"
    }
}

/// The pasteboard, behind a protocol so tests never touch the user's real clipboard.
@MainActor
protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// macOS 15.4+: whether reading other apps' content is allowed, asked about, or denied.
    var readPermission: ClipboardReadPermission { get }
    var types: [String] { get }
    func string() -> String?
    func imageData() -> Data?
    func fileURLs() -> [URL]
    /// Writes and returns the new change count (so Orilio's own write isn't recorded).
    func write(_ item: ClipItem, image: Data?) -> Int
}

enum ClipboardReadPermission: Equatable, Sendable {
    case allowed, ask, denied
}

@MainActor
final class SystemPasteboard: PasteboardAccess {
    private let board = NSPasteboard.general

    var changeCount: Int { board.changeCount }

    var readPermission: ClipboardReadPermission {
        if #available(macOS 15.4, *) {
            switch board.accessBehavior {
            case .alwaysAllow: return .allowed
            case .alwaysDeny: return .denied
            case .ask: return .ask
            default: return .allowed // never asked yet: the first read shows the system alert
            }
        }
        return .allowed
    }

    var types: [String] { board.types?.map(\.rawValue) ?? [] }
    func string() -> String? { board.string(forType: .string) }
    func imageData() -> Data? { board.data(forType: .png) ?? board.data(forType: .tiff) }

    func fileURLs() -> [URL] {
        board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
    }

    func write(_ item: ClipItem, image: Data?) -> Int {
        board.clearContents()
        switch item.kind {
        case .image:
            if let image, let picture = NSImage(data: image) { board.writeObjects([picture]) }
        case .files:
            board.writeObjects(item.fileURLs.map { $0 as NSURL })
        case .link:
            if let text = item.text {
                board.setString(text, forType: .string)
                board.setString(text, forType: .URL)
            }
        case .text, .code:
            board.setString(item.text ?? "", forType: .string)
        }
        return board.changeCount
    }
}
